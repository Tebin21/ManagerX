let css = '<style id="desktop-vector-icons-css">\n';
css += 'input, textarea, select, [contenteditable="true"], [tabindex] { outline: none !important; outline-style: none !important; outline-width: 0 !important; box-shadow: none !important; -webkit-tap-highlight-color: transparent !important; }\n';
css += '*:focus { outline: none !important; outline-style: none !important; }\n';
css += '*:focus-visible { outline: none !important; outline-style: none !important; }\n';
for (const vf of VECTOR_FONTS) {
  for (const alias of vf.aliases) {
    css += `@font-face {\n  font-family: '${alias}';\n  src: url('/fonts/${vf.name}.ttf') format('truetype');\n  font-display: block;\n}\n`;
  }
}
css += '</style>\n';
css += '<script>\n';
css += '  if (typeof window !== "undefined" && (window.location.pathname.endsWith("/index.html") || window.location.pathname.endsWith("index.html"))) {\n';
css += '    var clean = window.location.pathname.replace(/\\/?index\\.html$/, "") || "/";\n';
css += '    window.history.replaceState(null, "", clean + window.location.search + window.location.hash);\n';
css += '  }\n';
css += '</script>\n';

const earlyRedirectScript = '<script>(function(){if(typeof window!=="undefined"&&(window.location.pathname.endsWith("/index.html")||window.location.pathname.endsWith("index.html"))){var c=window.location.pathname.replace(/\\/?index\\.html$/,"")||"/";window.history.replaceState(null,"",c+window.location.search+window.location.hash);}})();</script>';

function injectHtml(targetPath) {
  if (!fs.existsSync(targetPath)) return;
  let html = fs.readFileSync(targetPath, 'utf-8');
  if (html.includes('id="desktop-vector-icons-css"')) {
    html = html.replace(/<style id="desktop-vector-icons-css">[\s\S]*?<\/style>/, css.trim());
  } else if (html.includes('</head>')) {
    html = html.replace('</head>', `${css}</head>`);
  }
  if (!html.includes('window.location.pathname.replace(/\\/?index\\.html$/')) {
    if (html.includes('<head>')) {
      html = html.replace('<head>', `<head>${earlyRedirectScript}`);
    } else {
      html = earlyRedirectScript + html;
    }
  }
  fs.writeFileSync(targetPath, html);
}

injectHtml(path.join(distDir, 'index.html'));
injectHtml(path.join(rootDir, 'dist/index.html'));

