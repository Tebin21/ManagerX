const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'desktop/dist');
const fontsDir = path.join(distDir, 'fonts');
const rootDistFonts = path.join(rootDir, 'dist/fonts');

fs.mkdirSync(fontsDir, { recursive: true });
fs.mkdirSync(rootDistFonts, { recursive: true });

function copyFileSafe(src, dest) {
  try {
    fs.copyFileSync(src, dest);
  } catch (e) {
    console.error(`Failed to copy ${src} to ${dest}:`, e.message);
  }
}

// 1. Copy Vector Icons directly from node_modules
const vectorFontsSrc = path.join(rootDir, 'node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts');
if (fs.existsSync(vectorFontsSrc)) {
  for (const f of fs.readdirSync(vectorFontsSrc)) {
    if (f.endsWith('.ttf')) {
      copyFileSafe(path.join(vectorFontsSrc, f), path.join(fontsDir, f));
      copyFileSafe(path.join(vectorFontsSrc, f), path.join(rootDistFonts, f));
    }
  }
}

// 2. Copy Kurdish fonts from assets/fonts
const customFontsSrc = path.join(rootDir, 'assets/fonts');
if (fs.existsSync(customFontsSrc)) {
  for (const f of fs.readdirSync(customFontsSrc)) {
    if (f.endsWith('.ttf')) {
      copyFileSafe(path.join(customFontsSrc, f), path.join(fontsDir, f));
      copyFileSafe(path.join(customFontsSrc, f), path.join(rootDistFonts, f));
    }
  }
}

// 3. Scan dist/assets recursively to capture any hashed font files generated by Expo
const distAssets = path.join(rootDir, 'dist/assets');
function scanAndCopyHashedFonts(dir) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      scanAndCopyHashedFonts(full);
    } else if (entry.name.endsWith('.ttf')) {
      // Copy with hashed name
      copyFileSafe(full, path.join(fontsDir, entry.name));
      copyFileSafe(full, path.join(rootDistFonts, entry.name));
      // Also copy with unhashed name if applicable
      const baseName = entry.name.split('.')[0] + '.ttf';
      copyFileSafe(full, path.join(fontsDir, baseName));
      copyFileSafe(full, path.join(rootDistFonts, baseName));
    }
  }
}
scanAndCopyHashedFonts(distAssets);

